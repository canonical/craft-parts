"""Version 2 of the Python plugin."""

import shlex
from textwrap import dedent
from typing import Literal

import pydantic
from typing_extensions import override

from craft_parts.plugins.base import Plugin
from craft_parts.plugins.properties import PluginProperties


class PythonPluginProperties(PluginProperties, frozen=True):
    """The part properties used by the python plugin."""

    plugin: Literal["python"] = "python"

    python_requirements: list[str] = pydantic.Field(
        default=[],
        description="List of paths to requirements files.",
    )
    """List of paths to requirements files.

    Use this key when dependencies must be installed from one or more explicit
    requirements files, such as ``requirements.txt``. The plugin does not
    automatically select a requirements file from the source tree; each file
    must be listed here.

    A part does not need this key when its dependencies are already declared by
    the project metadata used during package installation. For example, when
    the source contains a ``setup.py`` or ``pyproject.toml`` file, the plugin
    installs the project and pip resolves the dependencies declared by the
    package itself. That metadata may also come from configuration files such
    as ``setup.cfg``.
    """

    python_packages: list[str] = pydantic.Field(
        default=[],
        description="Additional Python packages to install with pip.",
    )
    """Additional Python packages to install with pip."""

    # part properties required by the plugin
    source: str


class PythonPlugin(Plugin):
    """Python plugin, version 2.

    Unlike the original Python plugin, this one does *not* require the creation of
    virtual environments to work. Instead, it uses pip's support for both a) installing
    directly into the user's base dir and b) using a Python interpreter that is not the
    one running pip initially. This allows lighter payloads as the -venv package is
    not required, and interacts well with usrmerged directories.

    The downside is that the payload generated by the plugin assumes that the primed
    contents will include the Python interpreter; if this is not the case, the runtime
    will need to add the payload to Python's path (e.g. via PYTHONPATH).

    pip embeds the build-time path of the interpreter that runs it in the shebangs of
    the console scripts it generates. Since that path only exists in the build
    environment, the plugin rewrites the shebangs of the scripts it installs to the
    value returned by :meth:`_get_runtime_python_interpreter`.
    """

    properties_class = PythonPluginProperties
    _options: PythonPluginProperties

    def _get_runtime_python_interpreter(self) -> str:
        """Obtain the path to the Python interpreter that is valid at runtime.

        pip generates console scripts whose shebangs contain the build-time path
        of the Python interpreter, which doesn't exist in the primed payload.
        This method returns the interpreter path that the shebangs are rewritten
        to, for use when the payload is deployed.

        This method can be overridden by application-specific subclasses to match
        the runtime layout of the payload, such as the interpreter's location in
        a snap or a chisel slice.

        The default assumes that the payload includes the Python interpreter at
        ``/usr/bin/python3``, which is where interpreter stage-packages install
        it on usrmerged systems.
        """
        return "/usr/bin/python3"

    @override
    def get_build_snaps(self) -> set[str]:
        """Return a set of required snaps to install in the build environment."""
        return set()

    @override
    def get_build_packages(self) -> set[str]:
        """Return a set of required packages to install in the build environment."""
        return set()

    @override
    def get_build_environment(self) -> dict[str, str]:
        """Return a dictionary with the environment to use in the build step."""
        return {
            "PIP_USER": "1",
            "PYTHONUSERBASE": str(self._part_info.part_install_dir),
            "PIP_BREAK_SYSTEM_PACKAGES": "1",
            "PIP_PYTHON": "$(which python3)",
        }

    @override
    def get_build_commands(self) -> list[str]:
        """Return a list of commands to run during the build step."""

        # Disallow using the system's Python interpreter for now. The issue is that
        # using the system interpreter will make pip skip dependencies that are already
        # installed in the system, even though they won't be part of the part's files.
        python_check = dedent("""\
          if [[ ${PIP_PYTHON} == /usr/bin/* ]]; then
            echo "Using the system Python interpreter is not supported." 1>&2
            exit 1
          fi
        """)

        pip_lines: list[str] = []

        # First the requirements
        requirements = " ".join(
            f"-r {shlex.quote(req)}" for req in self._options.python_requirements
        )
        pip_lines.append(f"REQUIREMENTS=({requirements})")

        # Then any extra packages
        packages = " ".join(shlex.quote(pkg) for pkg in self._options.python_packages)
        pip_lines.append(f"PACKAGES=({packages})")

        # Then finally the project in the source itself, if it exists
        project = dedent("""\
          if [ -f setup.py -o -f pyproject.toml ]; then
            PACKAGES+=(".")
          fi
        """)
        pip_lines.append(project)

        pip_lines.append('pip install "${REQUIREMENTS[@]}" "${PACKAGES[@]}"')

        pip_lines.append(self._get_rewrite_shebangs_command())

        # Add a sitecustomize so that the bundled Python interpreter (if any) will
        # pick up the packages installed by pip here
        sitecustomize = dedent("""\
          # Add a sitecustomize
          python_bin=${PIP_PYTHON}
          python_dir=python$($python_bin -c "import sys; print(f'{sys.version_info.major}.{sys.version_info.minor}')")
          mkdir -p ${CRAFT_PART_INSTALL}/lib/${python_dir}
          cat > ${CRAFT_PART_INSTALL}/lib/${python_dir}/sitecustomize.py << EOF
          import site
          import sys
          from pathlib import Path

          # Add the directory that contains the pip-installed packages.
          site_dir = Path(__file__).parent / "site-packages"
          site.addsitedir(str(site_dir))
          EOF
        """)

        return [python_check, *pip_lines, sitecustomize]

    def _get_rewrite_shebangs_command(self) -> str:
        """Return the command that fixes the shebangs of pip-installed scripts.

        pip generates console scripts whose shebangs point at the interpreter
        that ran pip, which is a build-time path that doesn't exist in the
        primed payload. When that path is longer than the kernel's shebang
        limit, pip instead emits a ``#!/bin/sh`` polyglot header of three lines
        with the interpreter path on the second line. Both forms are replaced
        with the interpreter from :meth:`_get_runtime_python_interpreter`.
        """
        script_interpreter = shlex.quote(self._get_runtime_python_interpreter())
        return dedent(f"""\
          # Rewrite the build-time shebangs of the scripts installed by pip.
          for script in "${{CRAFT_PART_INSTALL}}/bin"/*; do
            [[ -f ${{script}} && ! -L ${{script}} ]] || continue
            read -r shebang < "${{script}}" || continue
            if [[ ${{shebang}} == "#!${{PIP_PYTHON}}"* ]]; then
              sed -i "1 s|^#!${{PIP_PYTHON}}[^ ]*\\( .\\+\\)\\?$|#!{script_interpreter}\\1|" "${{script}}"
            elif [[ ${{shebang}} == "#!/bin/sh" ]]; then
              # Possibly pip's polyglot header for long interpreter paths; only
              # rewrite it if the second line executes the pip interpreter.
              if [[ $(sed -n 2p "${{script}}") == "'''exec' ${{PIP_PYTHON}} "* ]]; then
                sed -i "1,3 c #!{script_interpreter}" "${{script}}"
              fi
            fi
          done
        """)
